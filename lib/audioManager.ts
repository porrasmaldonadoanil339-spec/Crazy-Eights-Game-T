// ─── Core: serialized music transition with crossfade ────────────────────────
const FADE_MS = 380;
const FADE_STEPS = 10;

async function fadeOutCurrent() {
  const player = bgPlayer;
  if (!player) return;
  const startVol = player.volume;
  const stepDur = FADE_MS / FADE_STEPS;
  for (let i = 1; i <= FADE_STEPS; i++) {
    const v = startVol * (1 - i / FADE_STEPS);
    await safe(async () => { player.volume = Math.max(0, v); });
    await new Promise<void>((r) => setTimeout(r, stepDur));
  }
}

async function fadeInCurrent() {
  const player = bgPlayer;
  if (!player) return;
  const targetVol = musicVolume;
  const stepDur = FADE_MS / FADE_STEPS;
  await safe(async () => { player.volume = 0; });
  for (let i = 1; i <= FADE_STEPS; i++) {
    const v = targetVol * (i / FADE_STEPS);
    await safe(async () => { player.volume = Math.min(targetVol, v); });
    await new Promise<void>((r) => setTimeout(r, stepDur));
  }
}

function sourceForTrack(track: MusicTrack) {
  if (track === "menu") return SOUNDS.menuMusic;
  if (track === "search") return SOUNDS.searchMusic;
  return SOUNDS.gameMusic;
}

function getOrCreateTrackPlayer(track: MusicTrack): AudioPlayer | null {
  let p = trackPlayers.get(track) ?? null;
  if (p) return p;
  try {
    p = createAudioPlayer(sourceForTrack(track));
    p.volume = 0;
    p.loop = true;
    trackPlayers.set(track, p);
  } catch { p = null; }
  return p;
}

function getOrCreateAmbience(): AudioPlayer | null {
  if (ambiencePlayer) return ambiencePlayer;
  try {
    const p = createAudioPlayer(SOUNDS.casinoAmbience);
    p.loop = true;
    p.volume = 0;
    ambiencePlayer = p;
  } catch { ambiencePlayer = null; }
  return ambiencePlayer;
}

async function _startAmbienceInternal() {
  if (ambienceActive) return;
  if (!isMusicEnabled) return;
  const p = getOrCreateAmbience();
  if (!p) return;
  ambienceActive = true;
  await safe(async () => {
    p.volume = 0;
    p.play();
  });
  await fadePlayerTo(p, ambienceVolume);
}

async function _stopAmbienceInternal() {
  if (!ambiencePlayer || !ambienceActive) return;
  ambienceActive = false;
  const p = ambiencePlayer;
  await fadePlayerTo(p, 0);
  await safe(async () => { p.pause(); });
}

// Public ambience controls — serialized through `ambienceTransition` so a
// rapid sequence of menu↔game route changes can never overlap a fade-in with
// a fade-out on the same player.
async function startAmbience() {
  const prev = ambienceTransition ?? Promise.resolve();
  const next = prev.then(() => _startAmbienceInternal()).catch(() => {});
  ambienceTransition = next;
  await next;
  if (ambienceTransition === next) ambienceTransition = null;
}

async function stopAmbience() {
  const prev = ambienceTransition ?? Promise.resolve();
  const next = prev.then(() => _stopAmbienceInternal()).catch(() => {});
  ambienceTransition = next;
  await next;
  if (ambienceTransition === next) ambienceTransition = null;
}

// When set, the casino ambience layer is forced ON regardless of which music
// track is currently playing. Used during the Reto de Fichas run so the
// casino atmosphere bleeds under the in-game music for the whole match.
let forceAmbience = false;

async function syncAmbienceWithTrack(track: MusicTrack | null) {
  if (isMusicEnabled && (forceAmbience || track === "menu")) {
    await startAmbience();
  } else {
    await stopAmbience();
  }
}

export async function setForceAmbience(enabled: boolean): Promise<void> {
  if (forceAmbience === enabled) return;
  forceAmbience = enabled;
  await syncAmbienceWithTrack(currentTrack);
}

async function applyMusicTransition(track: MusicTrack, opts?: { sequential?: boolean }) {
  if (currentTrack === track && bgPlayer) {
    syncAmbienceWithTrack(track).catch(() => {});
    return;
  }
  if (!isMusicEnabled) return;

  const oldPlayer = bgPlayer;
  const newPlayer = getOrCreateTrackPlayer(track);

  // Sequential mode: fully fade out + pause the old track BEFORE starting the
  // new one. Used for ranked matchmaking → game so menu/search music never
  // overlaps the start of the game track.
  if (opts?.sequential) {
    if (oldPlayer && oldPlayer !== newPlayer) {
      await fadePlayerTo(oldPlayer, 0);
      await safe(async () => { oldPlayer.pause(); });
    }
    if (newPlayer) {
      await safe(async () => {
        newPlayer.volume = 0;
        newPlayer.play();
      });
      bgPlayer = newPlayer;
      currentTrack = track;
      await fadePlayerTo(newPlayer, musicVolume);
    }
    syncAmbienceWithTrack(track).catch(() => {});
    return;
  }

  // Default: true crossfade between persistent per-track players. Old player
  // is paused (NOT destroyed) so its position is preserved; next time we
  // switch back to it, playback resumes seamlessly from where it left off.
  if (newPlayer) {
    await safe(async () => {
      newPlayer.volume = 0;
      newPlayer.play();
    });
    bgPlayer = newPlayer;
    currentTrack = track;
  }
  await Promise.all([
    oldPlayer && oldPlayer !== newPlayer ? fadePlayerTo(oldPlayer, 0) : Promise.resolve(),
    newPlayer ? fadePlayerTo(newPlayer, musicVolume) : Promise.resolve(),
  ]);
  if (oldPlayer && oldPlayer !== newPlayer) {
    await safe(async () => { oldPlayer.pause(); });
  }
  syncAmbienceWithTrack(track).catch(() => {});
}

async function fadePlayerTo(player: any, targetVol: number) {
  const startVol = player.volume ?? 0;
  const stepDur = FADE_MS / FADE_STEPS;
  for (let i = 1; i <= FADE_STEPS; i++) {
    const t = i / FADE_STEPS;
    const v = startVol + (targetVol - startVol) * t;
    await safe(async () => { player.volume = Math.max(0, Math.min(1, v)); });
    await new Promise<void>((r) => setTimeout(r, stepDur));
  }
}

async function requestMusicTrack(track: MusicTrack, opts?: { sequential?: boolean }) {
  // Record the latest desired track
  lastRequestedTrack = track;
  pendingTrack = track;
  if (opts?.sequential) pendingSequential = true;

  // If a transition is already in progress, let it pick up pendingTrack when done
  if (transitionInProgress) return;

  transitionInProgress = true;
  try {
    // Keep processing until there's no more pending request
    while (pendingTrack !== null) {
      const target = pendingTrack;
      const seq = pendingSequential;
      pendingTrack = null;
      pendingSequential = false;
      await applyMusicTransition(target, { sequential: seq });
    }
  } finally {
    transitionInProgress = false;
  }
}

