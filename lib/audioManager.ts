// Per-mode in-game music routing. Until dedicated per-mode loops are
// produced, we re-use the existing two music tracks (game / search) to
// give high-stakes modes (Torneo, Ranked, Reto de Fichas) a more tense,
// suspenseful backdrop versus the standard game-music for casual modes.
//
// Goes through the same serialized requestMusicTrack pipeline as
// startGameMusic so transitions never overlap when modes switch.
const MODE_TO_MUSIC_TRACK: Record<string, MusicTrack> = {
  practice: "game",
  classic: "game",
  lightning: "game",
  challenge: "game",
  tournament: "search",
  ranked: "search",
  fichas: "search",
};

export async function startGameMusicForMode(
  modeId: string | undefined,
  opts?: { sequential?: boolean; isFichasRun?: boolean },
) {
  const key = opts?.isFichasRun ? "fichas" : (modeId ?? "classic");
  const track = MODE_TO_MUSIC_TRACK[key] ?? "game";
  await requestMusicTrack(track, opts);
}

async function _stopMusicInternal() {
  const player = bgPlayer;
  bgPlayer = null;
  currentTrack = null;
  await stopAmbience();
  if (!player) return;
  // Pause but DO NOT remove — we want to preserve playback position so
  // resuming the track later continues from the same point.
  await safe(async () => { player.pause(); });
}

export async function stopMusic() {
  pendingTrack = null; // Cancel any pending transition
  await _stopMusicInternal();
}

export async function resumeCurrentMusic() {
  if (!isMusicEnabled || !lastRequestedTrack) return;
  if (bgPlayer) return; // Already playing
  const track = lastRequestedTrack;
  await requestMusicTrack(track);
}

export async function pauseMusic() {
  if (!bgPlayer) return;
  await safe(async () => bgPlayer!.pause());
}

export async function resumeMusic() {
  if (!bgPlayer || !isMusicEnabled) return;
  await safe(async () => bgPlayer!.play());
}

export function getCurrentTrack(): MusicTrack | null {
  return currentTrack;
}

async function playSfx(key: SoundKey, volume?: number) {
  if (isSfxMuted) return;
  if (isBackgrounded) return;
  await safe(async () => {
    const player = getOrCreateSfx(key);
    player.volume = volume ?? sfxVolume;
    player.seekTo(0);
    player.play();
  });
}

export async function setAppBackgrounded(backgrounded: boolean) {
  isBackgrounded = backgrounded;
  if (backgrounded) {
    // Hard-stop every SFX player too so card sounds never bleed into the home screen
    for (const player of sfxPlayers.values()) {
      await safe(async () => { player.pause(); });
    }
    if (ambiencePlayer && ambienceActive) {
      await safe(async () => { ambiencePlayer!.pause(); });
    }
  } else {
    if (ambienceActive && ambiencePlayer && isMusicEnabled) {
      await safe(async () => { ambiencePlayer!.play(); });
    }
  }
}

function haptic(fn: () => Promise<void>) {
  if (Platform.OS !== "web" && isHapticEnabled) safe(fn);
}

