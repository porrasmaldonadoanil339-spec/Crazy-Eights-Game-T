// Premium logo stinger. Played once when the main menu first mounts (per
// app session) to give the brand a sonic identity, in the spirit of the
// Clash Royale boot sound. Respects the SFX toggle via `playSfx`. Includes
// a session-level guard so navigating back to the menu won't replay it
// during the same app launch (until next process restart).
let logoStingerPlayedThisSession = false;
let selectedLogoStingerId: LogoStingerId = DEFAULT_LOGO_STINGER_ID;

// Task #85 — runtime-loaded custom logo stinger (from a file:// URI). We keep
// the player cached so repeated previews / boot don't decode the file twice.
let customStingerUri: string | null = null;
let customStingerPlayer: AudioPlayer | null = null;
// Task #91 — saved custom clips are now real, pre-trimmed m4a files written
// to the document directory (the trim window is baked in by the server's
// ffmpeg endpoint at Save time). When customStingerIsTrimmedFile is true,
// playback just plays the file from the start and lets it end naturally.
// The start/end markers below are still applied (seek + scheduled pause)
// for legacy profiles created before #91 (where the file is the full
// untrimmed source) so they keep stopping at the 2-second budget.
let customStingerStartMs = 0;
let customStingerEndMs = CUSTOM_LOGO_STINGER_MAX_MS;
let customStingerIsTrimmedFile = false;
let customStingerStopTimer: ReturnType<typeof setTimeout> | null = null;

function sfxKeyForStinger(id: LogoStingerId): SoundKey {
  const entry = LOGO_STINGERS.find((s) => s.id === id);
  return entry?.sfxKey ?? "logoStingerCasino";
}

export function setLogoStingerId(id: LogoStingerId) {
  selectedLogoStingerId = id;
}

export function getLogoStingerId(): LogoStingerId {
  return selectedLogoStingerId;
}

// Task #85 — register/clear the URI of the user's custom intro clip. Pass
// null to drop the cached player (e.g. when the user removes their clip or
// picks a new file).
export function setCustomStingerUri(uri: string | null) {
  if (uri === customStingerUri) return;
  if (customStingerStopTimer) {
    clearTimeout(customStingerStopTimer);
    customStingerStopTimer = null;
  }
  if (customStingerPlayer) {
    try { customStingerPlayer.pause(); customStingerPlayer.remove(); } catch {}
    customStingerPlayer = null;
  }
  customStingerUri = uri;
}

export function getCustomStingerUri(): string | null {
  return customStingerUri;
}

function getOrCreateCustomStingerPlayer(): AudioPlayer | null {
  if (!customStingerUri) return null;
  if (customStingerPlayer) return customStingerPlayer;
  try {
    const p = createAudioPlayer({ uri: customStingerUri });
    p.volume = sfxVolume * 0.95;
    customStingerPlayer = p;
  } catch { customStingerPlayer = null; }
  return customStingerPlayer;
}

// Task #91 — register the trim markers for the saved custom clip. Post-#91
// callers always pass isTrimmedFile=true with 0..trimmedDurationMs (the file
// IS the trimmed clip, so playback skips the seek + scheduled pause). Legacy
// callers (or boot-time hydration of a pre-#91 profile) leave isTrimmedFile
// undefined / false; we keep the window length capped at the 2-second budget
// so the legacy safety stop never exceeds it.
export function setCustomStingerTrim(startMs: number, endMs: number, isTrimmedFile?: boolean) {
  const a = Math.max(0, Math.floor(startMs));
  const b = Math.max(a, Math.floor(endMs));
  customStingerStartMs = a;
  customStingerEndMs = Math.min(b, a + CUSTOM_LOGO_STINGER_MAX_MS);
  customStingerIsTrimmedFile = !!isTrimmedFile;
}

// Task #87 — preview an arbitrary [startMs, endMs] window of a draft clip
// (the user's pick before they've committed to Save). Owned end-to-end by the
// audio manager so the trim modal doesn't have to manage its own AudioPlayer:
// it caches one player per URI, scrubs to startMs, and schedules a pause at
// endMs. Bypasses the SFX mute toggle on purpose — the player tapped Preview.
let draftStingerPlayer: AudioPlayer | null = null;
let draftStingerUri: string | null = null;
let draftStingerStopTimer: ReturnType<typeof setTimeout> | null = null;

export async function previewCustomStingerWindow(
  uri: string,
  startMs: number,
  endMs: number,
): Promise<boolean> {
  if (isBackgrounded) return false;
  stopCustomStingerWindowPreview();
  if (draftStingerPlayer && draftStingerUri !== uri) {
    try { draftStingerPlayer.remove(); } catch {}
    draftStingerPlayer = null;
  }
  if (!draftStingerPlayer) {
    try {
      draftStingerPlayer = createAudioPlayer({ uri });
      draftStingerUri = uri;
    } catch {
      draftStingerPlayer = null;
      draftStingerUri = null;
      return false;
    }
  }
  const start = Math.max(0, startMs);
  const windowMs = Math.max(50, Math.min(CUSTOM_LOGO_STINGER_MAX_MS, endMs - start));
  const p = draftStingerPlayer;
  await safe(async () => {
    p.volume = sfxVolume * 0.95;
    p.seekTo(start / 1000);
    p.play();
  });
  draftStingerStopTimer = setTimeout(() => {
    draftStingerStopTimer = null;
    try { p.pause(); } catch {}
  }, windowMs);
  return true;
}

export function stopCustomStingerWindowPreview() {
  if (draftStingerStopTimer) {
    clearTimeout(draftStingerStopTimer);
    draftStingerStopTimer = null;
  }
  if (draftStingerPlayer) {
    try { draftStingerPlayer.pause(); } catch {}
  }
}

export function releaseCustomStingerWindowPreview() {
  stopCustomStingerWindowPreview();
  if (draftStingerPlayer) {
    try { draftStingerPlayer.remove(); } catch {}
  }
  draftStingerPlayer = null;
  draftStingerUri = null;
}

async function playStingerById(id: LogoStingerId, volume: number): Promise<boolean> {
  if (isSfxMuted || isBackgrounded) return false;
  if (id === "custom") {
    const p = getOrCreateCustomStingerPlayer();
    if (!p) return false;
    // Task #91 — when isTrimmedFile=true the saved file IS the trimmed clip,
    // so just play from the start and let it end naturally. Pre-#91 (legacy)
    // profiles still need the seek + scheduled-pause trick to honour the
    // 2-second budget against a longer untrimmed source.
    if (customStingerStopTimer) {
      clearTimeout(customStingerStopTimer);
      customStingerStopTimer = null;
    }
    if (customStingerIsTrimmedFile) {
      await safe(async () => {
        p.volume = volume;
        p.seekTo(0);
        p.play();
      });
    } else {
      const startSec = customStingerStartMs / 1000;
      const windowMs = Math.min(
        CUSTOM_LOGO_STINGER_MAX_MS,
        Math.max(50, customStingerEndMs - customStingerStartMs),
      );
      await safe(async () => {
        p.volume = volume;
        p.seekTo(startSec);
        p.play();
      });
      customStingerStopTimer = setTimeout(() => {
        customStingerStopTimer = null;
        try { p.pause(); } catch {}
      }, windowMs);
    }
    return true;
  }
  await playSfx(sfxKeyForStinger(id), volume);
  return true;
}

export async function playLogoStinger() {
  if (logoStingerPlayedThisSession) return;
  logoStingerPlayedThisSession = true;
  // If the player picked the custom slot but their clip is missing (e.g. the
  // file was deleted), silently fall back to the default built-in stinger.
  const played = await playStingerById(selectedLogoStingerId, sfxVolume * 0.95);
  if (!played && selectedLogoStingerId === "custom") {
    await playStingerById(DEFAULT_LOGO_STINGER_ID, sfxVolume * 0.95);
  }
}

