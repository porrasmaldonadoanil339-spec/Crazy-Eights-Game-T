export function syncSettings(
  musicEnabled: boolean,
  sfxEnabled: boolean,
  vibrationEnabled?: boolean,
  voiceFxEnabled?: boolean,
) {
  isMusicEnabled = musicEnabled;
  isSfxMuted = !sfxEnabled;
  if (vibrationEnabled !== undefined) isHapticEnabled = vibrationEnabled;
  if (voiceFxEnabled !== undefined) isVoiceFxEnabled = voiceFxEnabled;
  if (!musicEnabled && bgPlayer) {
    pauseMusic().catch(() => {});
    stopAmbience().catch(() => {});
  } else if (musicEnabled && bgPlayer) {
    resumeMusic().catch(() => {});
    if (currentTrack === "menu") startAmbience().catch(() => {});
  }
}

